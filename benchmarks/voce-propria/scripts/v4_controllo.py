"""V-4, part A step 4: the short automatic check of the current official model.

Two voices: giovanni (Common Voice Italian, CC0; Kyutai's recording) and F1 (Enrica Giampieretti,
LibriVox, public domain; the 25 s reference of V-m, internal measure only). The five test sentences and
the sixteen short phrases of V-1, two seeds each, generated by:
- onnx: Kalliope's graphs (flow LM with 8-bit weights, MatMulNBits) through the official loop
  (scripts/v4_onnx.py), the voice cloned from the recording by mimi_encoder.onnx;
- pt: the official PyTorch code (fp32), the voice cloned by get_state_for_audio_prompt.
Judged as in V-1 (scripts/v1_valuta.py): Whisper small, Kalliope-normalized on both sides, short
phrases with 0.5 s of silence around them; first word right; word errors; ECAPA of the sentences
against the voice (giovanni: the recording; F1: the centroid of her held-out clips, as in V-m).

Writes AUDIO/v4/controllo/<impl>/<voice>/s<seed>/<f|b><id>.wav and ESITI/v4/controllo.json.
Usage: python -I v4_controllo.py genera onnx|pt ; python -I v4_controllo.py valuta
"""
from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np  # noqa: E402

from comune import AUDIO, ESITI, MODELLI, PERSONE, leggi, picco_mb, scrivi  # noqa: E402
from v4_comune import REGISTRAZIONI  # noqa: E402

VOCI = {"giovanni": REGISTRAZIONI["giovanni"], "F1": PERSONE / "F1" / "riferimento.wav"}
SEMI = (1, 2)
BASE = AUDIO / "v4" / "controllo"


def genera(impl: str):
    os.environ["OMP_NUM_THREADS"] = "2"
    from v1_genera import testi
    tt = testi()
    tempi = {}
    if impl == "onnx":
        from v4_onnx import PocketV4
        p = PocketV4(MODELLI / "pocket-onnx-v4" / "italian")
        for v, rec in VOCI.items():
            past = p.stato_da_registrazione(leggi(rec, 24000))
            t0, durata = time.time(), 0.0
            for seme in SEMI:
                for kind, i, testo, _ in tt:
                    a = p.dici(past, testo, seme * 1000 + i)
                    durata += len(a) / 24000
                    scrivi(BASE / impl / v / f"s{seme}" / f"{kind}{i}.wav", a)
            tempi[v] = {"secondi": time.time() - t0, "audio_s": durata}
            print(impl, v, tempi[v], flush=True)
    else:
        import torch
        from v4_comune import modello
        m = modello(6, 0.3)
        for v, rec in VOCI.items():
            st = m.get_state_for_audio_prompt(Path(rec))
            t0, durata = time.time(), 0.0
            for seme in SEMI:
                for kind, i, testo, _ in tt:
                    torch.manual_seed(seme * 1000 + i)
                    a = m.generate_audio(st, testo, copy_state=True).numpy()
                    durata += len(a) / 24000
                    scrivi(BASE / impl / v / f"s{seme}" / f"{kind}{i}.wav", a)
            tempi[v] = {"secondi": time.time() - t0, "audio_s": durata}
            print(impl, v, tempi[v], flush=True)
    path = ESITI / "v4" / "controllo_tempi.json"
    old = json.loads(path.read_text()) if path.exists() else {}
    old[impl] = {"voci": tempi, "picco_mb": picco_mb()}
    path.write_text(json.dumps(old, ensure_ascii=False, indent=1))


def valuta():
    from comune import normalizza_kalliope, ricampiona
    from misure import Ecapa, Whisper, centroide, clip_persona, coseno, norm_parole
    from v1_genera import testi
    from v1_valuta import prima_ok
    W, E = Whisper(2), Ecapa(2)
    rif = {"giovanni": E.emb_audio(ricampiona(leggi(VOCI["giovanni"], 24000), 24000, 16000)),
           "F1": centroide([E.emb(f) for f in clip_persona("F1", "tenuto")])}
    tt = {(k, i): (testo, ref) for k, i, testo, ref in testi()}
    out_path = ESITI / "v4" / "controllo.json"
    cache = {r["file"]: r for r in json.loads(out_path.read_text())["righe"]} if out_path.exists() else {}
    righe = []
    for wav in sorted(BASE.glob("*/*/s*/*.wav")):
        rel = str(wav.relative_to(BASE))
        key = f"{rel}:{wav.stat().st_mtime_ns}"
        if key in cache:
            righe.append(cache[key])
            continue
        impl, voce, seme, nome = wav.parts[-4], wav.parts[-3], int(wav.parent.name[1:]), wav.stem
        kind, i = nome[0], int(nome[1:])
        testo, ref = tt[(kind, i)]
        a = leggi(wav)
        a_w = np.concatenate([np.zeros(12000, np.float32), a, np.zeros(12000, np.float32)]) if kind == "b" else a
        w = W.wer_frase(a_w, 24000, ref)
        hyp_w = norm_parole(normalizza_kalliope([w["trascrizione"]])[0])
        r = {"file": key, "impl": impl, "voce": voce, "seme": seme, "tipo": kind, "id": i, "testo": testo,
             "durata_s": len(a) / 24000, **w, "prima_ok": prima_ok(norm_parole(ref), hyp_w)}
        if kind == "f":
            r["ecapa"] = coseno(E.emb_audio(ricampiona(a, 24000, 16000)), rif[voce])
        righe.append(r)
    out_path.write_text(json.dumps({"righe": righe}, ensure_ascii=False, indent=1))
    for impl in sorted({r["impl"] for r in righe}):
        for voce in VOCI:
            for kind in ("f", "b"):
                rr = [r for r in righe if r["impl"] == impl and r["voce"] == voce and r["tipo"] == kind]
                if not rr:
                    continue
                e, n = sum(r["errori"] for r in rr), sum(r["parole"] for r in rr)
                s = (f"{impl:5s} {voce:9s} {'frasi' if kind == 'f' else 'brevi'}: prima parola persa "
                     f"{sum(not r['prima_ok'] for r in rr)}/{len(rr)}, WER {100 * e / n:.1f}%")
                if kind == "f":
                    s += f", ECAPA {np.mean([r['ecapa'] for r in rr]):.3f}"
                print(s, flush=True)


if __name__ == "__main__":
    if sys.argv[1] == "genera":
        genera(sys.argv[2])
    else:
        valuta()
