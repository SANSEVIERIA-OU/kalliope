"""V-1: the export against Kyutai's own code, on a voice Kyutai publishes (no cloning).

The official model with voice cloning is gated (account needed); the weights of
kyutai/pocket-tts-without-voice-cloning are open, and so are the precomputed states of the
predefined voices. With the predefined Italian voice "giovanni" (state regenerated by Kyutai with
end_on_pause, PR #334) both implementations start from the same state:

1. parity: temperature 0 (no sampling noise), the same sentence, latents of the official PyTorch
   code against our loop on the ONNX graphs (fp32 flow LM with free cache length, and int8);
2. first word: the five test sentences and the sixteen short phrases with the official code
   (generate_audio, temperature 0.3) and with our loop (official settings), two seeds each,
   written to AUDIO/v1/<pt|onnx>-giovanni/G/s<seed>/ for v1_valuta.py.

No cloning is done with the open weights: only the published voice states are used.
Usage: python -I v1_ufficiale.py [--parita] [--prima]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np  # noqa: E402

from comune import AUDIO, CODICE, ESITI, MODELLI, Cronometro, frasi, scrivi  # noqa: E402

REPO = CODICE / "dl-pocket-tts" / "pocket-tts-8ef5cbc7ccb880e999ed041f015aaf7931b49205"
BASE = MODELLI / "pocket-tts-senza-clonazione"
# "attuale": the Italian model since 24/9/2026 (new tokenizer), pinned by the official config;
# "vecchio": the Italian release of May 2026 (rev e7205b6e), the one the ONNX export was made from
# (same tokenizer.model, sha256 6583b974...).
VERSIONI = {
    "attuale": dict(pesi=BASE / "italian" / "model.safetensors", tok=BASE / "italian" / "tokenizer.json",
                    tipo="tokenizers", voce=BASE / "voci" / "giovanni.safetensors"),
    "vecchio": dict(pesi=BASE / "italian-vecchio" / "model.safetensors", tok=BASE / "italian-vecchio" / "tokenizer.model",
                    tipo="sentencepiece", voce=BASE / "italian-vecchio" / "embeddings" / "giovanni.safetensors"),
}
VOCE = VERSIONI["vecchio"]["voce"]


def modello_ufficiale(temp: float, versione: str = "vecchio"):
    import torch
    torch.set_num_threads(2)
    sys.path.insert(0, str(REPO))
    import yaml
    from pocket_tts.models.tts_model import TTSModel
    cfg = yaml.safe_load((REPO / "pocket_tts" / "config" / "italian.yaml").read_text())
    v = VERSIONI[versione]
    cfg["weights_path"] = str(v["pesi"])
    cfg.pop("weights_path_without_voice_cloning", None)
    cfg["flow_lm"]["lookup_table"]["tokenizer_path"] = str(v["tok"])
    cfg["flow_lm"]["lookup_table"]["tokenizer"] = v["tipo"]
    tmp = Path("/tmp/voce-m-pocketcfg")
    tmp.mkdir(exist_ok=True)
    (tmp / f"italian_{versione}.yaml").write_text(yaml.safe_dump(cfg))
    m = TTSModel.load_model(config=str(tmp / f"italian_{versione}.yaml"), temp=temp)
    m.voce_giovanni = str(v["voce"])
    return m


def latenti_ufficiali(m, testo: str, n: int):
    """The official autoregressive loop (TTSModel._generate) with latents collected instead of decoded."""
    import copy
    import queue
    import threading
    from pocket_tts.models.text_chunking import prepare_text_prompt
    st = copy.deepcopy(m.get_state_for_audio_prompt(m.voce_giovanni))
    txt, _ = prepare_text_prompt(testo, m.pad_with_spaces_for_short_inputs, m.remove_semicolons,
                                 m.append_terminal_punctuation, m.capitalize_first_letter, m.replace_characters)
    prepared = m.flow_lm.conditioner.prepare(txt)
    q, rq = queue.Queue(), queue.Queue()
    m._generate(model_state=st, prepared=prepared, max_gen_len=n, frames_after_eos=1000, latents_queue=q,
                result_queue=rq, stop=threading.Event())
    out = []
    while True:
        x = q.get()
        if x is None:
            break
        out.append(x.numpy())
    return np.concatenate(out, axis=1)


def pocket_giovanni(main: str, temp: float):
    from pocket import Pocket
    p = Pocket(threads=2, bundle="italian", main=main, temperatura=temp)
    ms = p.t._import_model_state_file(VOCE)
    p.stato_voce = p.t._state_from_model_state(ms, p.t.flow_state_manifest)
    return p


def parita():
    m = modello_ufficiale(0.0, "vecchio")
    testo = frasi()[3]["normalizzato"].split("?")[0] + "?"
    ref = latenti_ufficiali(m, testo, 40)
    out = {"testo": testo}
    for main in ("fp32", "int8"):
        p = pocket_giovanni(main, 0.0)
        p.min_eos = 10_000
        chunk = p.t._split_into_best_sentences(testo)[0]
        lat = []
        for i, x in enumerate(p._latenti(chunk, 0)):
            lat.append(x)
            if i + 1 >= ref.shape[1]:
                break
        onx = np.concatenate(lat, axis=1)
        n = min(onx.shape[1], ref.shape[1])
        d = np.abs(onx[0, :n] - ref[0, :n]).max(1)
        cos = (onx[0, :n] * ref[0, :n]).sum(1) / (np.linalg.norm(onx[0, :n], axis=1) * np.linalg.norm(ref[0, :n], axis=1))
        out[main] = {"passi": int(n), "diff_max_primi_5": [float(x) for x in d[:5]], "diff_max": float(d.max()),
                     "coseno_min": float(cos.min()), "coseno_medio": float(cos.mean())}
        print(main, out[main], flush=True)
    (ESITI / "v1" / "parita.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))


def prima():
    """First-word test on giovanni: the export (old model, our loop, official settings), the old
    model in the official code, and the current official model."""
    import torch
    from v1_genera import testi
    rep = []
    impl = {"pt-vecchio-giovanni": modello_ufficiale(0.3, "vecchio"), "pt-attuale-giovanni": modello_ufficiale(0.3, "attuale")}
    p = pocket_giovanni("int8", 0.3)
    for seme in (0, 1):
        for kind, i, testo, _ in testi():
            s_ = 1000 * seme + i + (0 if kind == "f" else 100)
            for nome, m in impl.items():
                torch.manual_seed(s_)
                c = Cronometro()
                a = m.generate_audio(m.get_state_for_audio_prompt(m.voce_giovanni), testo, copy_state=True).numpy()
                w, cpu = c.fine()
                scrivi(AUDIO / "v1" / nome / "G" / f"s{seme}" / f"{kind}{i}.wav", a)
                rep.append({"impl": nome, "seme": seme, "tipo": kind, "id": i, "cpu_s": cpu, "audio_s": len(a) / 24000})
            c = Cronometro()
            b, st = p.dici(testo, seme=s_)
            w, cpu = c.fine()
            scrivi(AUDIO / "v1" / "onnx-giovanni" / "G" / f"s{seme}" / f"{kind}{i}.wav", b)
            rep.append({"impl": "onnx-giovanni", "seme": seme, "tipo": kind, "id": i, "cpu_s": cpu, "audio_s": len(b) / 24000})
        print("seme", seme, flush=True)
    (ESITI / "v1" / "genera_giovanni.json").write_text(json.dumps(rep, indent=1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--parita", action="store_true")
    ap.add_argument("--prima", action="store_true")
    a = ap.parse_args()
    os.environ["OMP_NUM_THREADS"] = "2"
    if a.parita:
        parita()
    if a.prima:
        prima()


if __name__ == "__main__":
    main()
