"""The catalogues of the website: the template made from the pages, the merge into each language, and the check.

website/lingue/site.pot   the template: one entry per message, keyed by `msgctxt` (the key written in the page)
website/lingue/it.po      Italian, the language of the pages: generated, never edited
website/lingue/<xx>.po    one file per language: adding a language is adding this file

An entry is known by its `msgctxt`. When the Italian text of a key changes, the translation stays in the file, marked
`#, fuzzy` with the old text in `#| msgid`, and the language is not published until someone has read it again.
"""
import pathlib
import re

from . import app, cldr, menu, pagina, plurali, po

PROGETTO = "Kalliope"


# ---------- raccogliere i messaggi dalle pagine ----------
def pagine_html(sito):
    return sorted(p for p in pathlib.Path(sito).rglob("*.html") if "lingue" not in p.relative_to(sito).parts[:1])


def raccogli(sito, crates=None):
    """({pagina: (testo, radice, messaggi)}, messaggi in ordine, errori). Solo le pagine che segnano qualcosa. Con `crates`
    (la cartella crates/ del programma) i messaggi del programma, `@tr` e `tr!`, vengono dopo quelli delle pagine."""
    sito = pathlib.Path(sito)
    pagine, errori, tutti = {}, [], {}
    for f in pagine_html(sito):
        rel = f.relative_to(sito).as_posix()
        t = f.read_text(encoding="utf-8")
        if not pagina.pagina_traducibile(t):
            continue
        try:
            radice = pagina.leggi(t)
        except pagina.ErrorePagina as e:
            errori.append(f"{rel}: {e}")
            continue
        msgs, err = pagina.messaggi(t, radice, rel)
        errori.extend(err)
        errori.extend(pagina.non_segnato(t, radice, rel))
        pagine[rel] = (t, radice, msgs)
        for m in msgs:
            if m.chiave in tutti:
                a = tutti[m.chiave]
                if a.testo != m.testo or a.plurale != m.plurale:
                    errori.append(f"{rel}:{m.riga}: the key «{m.chiave}» has another text in {a.pagina}:{a.riga}")
                continue
            tutti[m.chiave] = m
    for chiave in [k for k in tutti if k.startswith("programma.")]:
        errori.append(f"{tutti[chiave].pagina}:{tutti[chiave].riga}: the key «{chiave}» starts with programma.: that is for the program's messages")
    if crates is not None:
        msgs, err = app.raccogli(crates)
        errori.extend(err)
        for chiave, m in msgs.items():
            tutti[chiave] = m
        # la voce del menu delle applicazioni (packaging/linux/*.desktop.in, accanto a crates/): messaggi del programma anche lei
        msgs, err = menu.raccogli(pathlib.Path(crates).parent)
        errori.extend(err)
        for chiave, m in msgs.items():
            if chiave in tutti:
                errori.append(f"{m.pagina}:{m.riga}: the key «{chiave}» is used by the program too: write two keys")
            else:
                tutti[chiave] = m
    return pagine, tutti, errori


def _legenda_tag(m, doc):
    righe = []
    for i, nodo in enumerate(m.tag, 1):
        tag = doc[nodo.s:nodo.se]
        righe.append(f"<{i}> = {tag[:90]}")
    return righe


def intestazione(codice, nplurals_espr=None):
    h = {"Project-Id-Version": PROGETTO, "MIME-Version": "1.0", "Content-Type": "text/plain; charset=UTF-8",
         "Content-Transfer-Encoding": "8bit"}
    if codice:
        h["Language"] = codice
        h["Plural-Forms"] = cldr.info(codice)["plurali"]["intestazione"]
    else:
        h["Language"] = ""
        h["Plural-Forms"] = "nplurals=INTEGER; plural=EXPRESSION;"
    return h


def modello(pagine, tutti):
    """Il modello (.pot) dalle pagine."""
    cat = po.Catalogo()
    cat.intestazione_commenti = ["Kalliope · texts of the website and of the program (template).", "Generated by tools/translations.py extract: do not edit by hand.",
                                 "Every entry has its key in msgctxt; the tags <1>…</1> and the placeholders {…} are left as they are.",
                                 "Keys «programma.…» are the messages of the program (the window, the status lines, the errors); the others are the website's."]
    cat.intestazione = intestazione(None)
    usi = {}
    for rel, (t, radice, msgs) in pagine.items():
        for m in msgs:
            usi.setdefault(m.chiave, []).append(rel)
    for chiave, m in tutti.items():
        v = po.Voce(ctx=chiave, id=m.testo, id_plurale=m.plurale, str=[""] if m.plurale is None else [])
        if m.tipo == "app":
            if m.nota:
                v.estratti.append(m.nota)
            ph = list(dict.fromkeys(app.nomi_segnaposto(m.testo + " " + (m.plurale or ""), m.formato)))
            if m.formato == "desktop":
                v.estratti.append("A line of the desktop file (the applications menu): plain text on one line, no tags, no backslash.")
            if m.formato == "slint" and ph:
                v.estratti.append("Placeholders: {} or {0} {1}… are the arguments, in order; {n} is the count of a plural. "
                                  "Leave them as they are; a translation may reorder them.")
            elif ph:
                v.estratti.append("Placeholders to leave as they are: " + " ".join("{" + p + "}" for p in ph))
            v.riferimenti = sorted(m.usi or {m.pagina})
            v.flags.append({"slint": "kalliope-slint", "rust": "kalliope-rust", "desktop": "kalliope-desktop"}[m.formato])
            if app.segnaposto(m.testo + " " + (m.plurale or "")):
                v.flags.append("python-brace-format")
            cat.voci.append(v)
            continue
        doc = pagine[m.pagina][0]
        if m.nota:
            v.estratti.append(m.nota)
        if m.tipo == "attributo":
            v.estratti.append(f"Attribute «{m.attr}» of an element of the page: plain text, no tags.")
        if m.tag:
            v.estratti.append("Tags in the text (move the words, keep every tag, each inside the same tag):")
            v.estratti.extend("  " + r for r in _legenda_tag(m, doc))
        ph = [p for p in dict.fromkeys(pagina.segnaposto(m.testo + " " + (m.plurale or "")))]
        if ph:
            v.estratti.append("Placeholders to leave as they are: " + " ".join(ph))
        v.riferimenti = sorted(set(usi[chiave]))
        if m.tipo == "contenuto":
            v.flags.append("kalliope-markup")   # il testo è un pezzo di HTML: tag numerati, &amp; &lt; &gt;
        if re.search(r"\{[A-Za-z_]", m.testo + (m.plurale or "")):
            v.flags.append("python-brace-format")
        cat.voci.append(v)
    return cat


# ---------- unire il modello a una lingua ----------
def forme_di(codice):
    return cldr.info(codice)["plurali"]["forme"]


def _vuote(n):
    return [""] * n


def unisci(vecchio, mod, codice, sorgente=False):
    """Il catalogo della lingua aggiornato al modello: voci nuove vuote, testo cambiato «fuzzy», voci tolte «obsolete»."""
    nuovo = po.Catalogo()
    nuovo.intestazione_commenti = vecchio.intestazione_commenti if vecchio else [f"Kalliope · texts of the website and of the program in {codice}."]
    nuovo.intestazione = dict(vecchio.intestazione) if vecchio and vecchio.intestazione else intestazione(codice)
    nuovo.intestazione.setdefault("Language", codice)
    precedenti = vecchio.per_chiave() if vecchio else {}
    forme = forme_di(codice)
    for v in mod.voci:
        n = po.Voce(ctx=v.ctx, id=v.id, id_plurale=v.id_plurale)
        n.estratti, n.riferimenti = list(v.estratti), list(v.riferimenti)
        n.flags = [f for f in v.flags]
        n.traduttore = []
        nf = 1 if v.id_plurale is None else len(forme)
        if sorgente:
            if v.id_plurale is None:
                n.str = [v.id]
            else:
                n.str = [v.id if f == "one" else v.id_plurale for f in forme]
            nuovo.voci.append(n); continue
        p = precedenti.get(v.ctx)
        if p is None:
            n.str = _vuote(nf)
        else:
            n.traduttore = list(p.traduttore)
            n.str = list(p.str) + _vuote(max(0, nf - len(p.str)))
            n.str = n.str[:nf] if v.id_plurale is not None else n.str[:1]
            if p.id == v.id and p.id_plurale == v.id_plurale:
                if p.fuzzy:
                    n.flags.append("fuzzy")
                    n.prec_id, n.prec_plurale = p.prec_id, p.prec_plurale
            else:
                n.flags.append("fuzzy")
                n.prec_id, n.prec_plurale = p.prec_id if p.fuzzy and p.prec_id is not None else p.id, p.id_plurale
        nuovo.voci.append(n)
    if vecchio:
        chiavi = {v.ctx for v in mod.voci}
        for v in vecchio.voci:
            if v.obsoleta or v.ctx not in chiavi:
                v.obsoleta = True
                nuovo.voci.append(v)
    return nuovo


# ---------- il controllo ----------
class Esito:
    def __init__(self, codice):
        self.codice = codice
        self.errori, self.mancanti, self.fuori_data, self.fuzzy, self.obsoleti = [], [], [], [], []

    @property
    def completa(self):
        return not (self.errori or self.mancanti or self.fuori_data or self.fuzzy)

    def riassunto(self, totale):
        parti = []
        if self.errori: parti.append(f"{len(self.errori)} errors")
        if self.mancanti: parti.append(f"{len(self.mancanti)} missing")
        if self.fuori_data: parti.append(f"{len(self.fuori_data)} with changed Italian text")
        if self.fuzzy: parti.append(f"{len(self.fuzzy)} fuzzy")
        fatte = totale - len(self.mancanti) - len(self.fuori_data) - len(self.fuzzy)
        return f"{self.codice}: {fatte}/{totale} entries ready" + (" (" + ", ".join(parti) + ")" if parti else "")


def controlla(cat, mod, codice):
    """Controlla il catalogo di una lingua contro il modello. Solo la libreria standard; tutto in un oggetto Esito."""
    e = Esito(codice)
    try:
        info = cldr.info(codice)
    except KeyError as x:
        e.errori.append(str(x)); return e
    h = cat.intestazione
    if h.get("Language") and h["Language"] != codice:
        e.errori.append(f"header: Language «{h['Language']}» but the file is «{codice}»")
    if "utf-8" not in h.get("Content-Type", "").lower():
        e.errori.append("header: Content-Type must say charset=UTF-8")
    for problema in plurali.confronta(info["plurali"]["regole"], h.get("Plural-Forms", "")):
        e.errori.append(f"header: Plural-Forms: {problema}")
    nforme = len(info["plurali"]["forme"])
    ctx_visti = set()
    voci = {}
    for v in cat.voci:
        if v.obsoleta:
            e.obsoleti.append(v.ctx); continue
        if v.ctx in ctx_visti:
            e.errori.append(f"{v.ctx}: the key is there twice")
        ctx_visti.add(v.ctx)
        voci[v.ctx] = v
    for t in mod.voci:
        v = voci.get(t.ctx)
        if v is None:
            e.mancanti.append(t.ctx); continue
        if v.id != t.id or v.id_plurale != t.id_plurale:
            e.fuori_data.append(t.ctx); continue
        if v.fuzzy:
            e.fuzzy.append(t.ctx); continue
        if t.id_plurale is None:
            if len(v.str) != 1:
                e.errori.append(f"{t.ctx}: has {len(v.str)} forms but the message is not a plural"); continue
            if not v.str[0].strip():
                e.mancanti.append(t.ctx); continue
            _controlla_testo(e, t, v.str[0], t.id, uguali=True)
        else:
            if len(v.str) != nforme:
                e.errori.append(f"{t.ctx}: has {len(v.str)} forms, the language needs {nforme} ({', '.join(info['plurali']['forme'])})"); continue
            if any(not s.strip() for s in v.str):
                e.mancanti.append(t.ctx); continue
            for s in v.str:
                _controlla_testo(e, t, s, t.id_plurale, uguali=False)
    return e


def _controlla_testo(e, t, tradotto, sorgente, uguali):
    if "kalliope-slint" in t.flags or "kalliope-rust" in t.flags:   # un messaggio del programma
        e.errori.extend(app.controlla_testo(t, tradotto, not uguali))
        return
    if "kalliope-desktop" in t.flags:   # una riga della voce del menu delle applicazioni
        e.errori.extend(menu.controlla_testo(t, tradotto))
        return
    a, b = pagina.segnaposto(sorgente), pagina.segnaposto(tradotto)
    if uguali:
        if a != b:
            e.errori.append(f"{t.ctx}: placeholders differ from the original: {' '.join(a) or '(none)'} → {' '.join(b) or '(none)'}")
    else:
        extra = [x for x in b if x not in a]
        if extra:
            e.errori.append(f"{t.ctx}: placeholders the original does not have: {' '.join(extra)}")
    if "kalliope-markup" not in t.flags:
        return
    for problema in pagina.verifica_tag(sorgente, tradotto):
        e.errori.append(f"{t.ctx}: {problema}")


# ---------- il file di una lingua ----------
def leggi_lingua(cartella, codice):
    f = pathlib.Path(cartella) / f"{codice}.po"
    return po.leggi(f.read_text(encoding="utf-8")) if f.exists() else None


def lingue_presenti(cartella):
    cartella = pathlib.Path(cartella)
    return sorted(f.stem for f in cartella.glob("*.po")) if cartella.exists() else []
