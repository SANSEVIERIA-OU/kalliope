const pw = await import(process.env.PLAYWRIGHT);
const [vero, dieci] = process.argv.slice(2);
const sleep = ms => new Promise(r => setTimeout(r, ms));
const b = await pw.chromium.launch({headless: true});
const ctx = await b.newContext({javaScriptEnabled: false, viewport: {width: 1440, height: 900}}); const p = await ctx.newPage();
await p.goto(vero + '/', {waitUntil: 'load'}); await sleep(1500); console.log('vero / senza JS →', p.url());
await p.goto(vero + '/installa/?x=1#y', {waitUntil: 'load'}); await sleep(1500); console.log('vero /installa/ senza JS →', p.url());
await p.goto(dieci + '/ar/', {waitUntil: 'load'}); await sleep(800);
await p.click('details.lingua-scelta summary'); await sleep(300);
console.log('ar selettore senza JS aperto:', await p.evaluate(() => document.querySelector('details.lingua-scelta').open));
await p.screenshot({path: '/tmp/lavoro-2s-foto/ritagli/senzajs-ar-selettore.png'});
await p.click('details.lingua-scelta a[hreflang="de"]'); await sleep(800); console.log('clic su Deutsch →', p.url());
await p.goto(dieci + '/', {waitUntil: 'load'}); await sleep(800);
await p.screenshot({path: '/tmp/lavoro-2s-foto/ritagli/senzajs-scelta.png'});
console.log('scelta senza JS, collegamenti:', await p.evaluate(() => document.querySelectorAll('.lingue-in-bolla a').length));
const c2 = await b.newContext({javaScriptEnabled: false, viewport: {width: 390, height: 844}}); const q = await c2.newPage();
await q.goto(dieci + '/it/non-ancora/', {waitUntil: 'load'}); await sleep(800);
await q.click('.pulsante-menu'); await sleep(500); console.log('telefono senza JS, Menu →', q.url());
await q.screenshot({path: '/tmp/lavoro-2s-foto/ritagli/senzajs-menu-390.png'});
await b.close();
